#!/usr/bin/env python3
"""
生成ASAP运行时恢复逻辑的汇编代码
实现_asap_restore函数，包含W*选择、U(W*)计算和状态恢复
"""

import json
import argparse
from pathlib import Path
from typing import Dict, List, Set

def generate_restore_function(metadata: Dict) -> List[str]:
    """
    生成_asap_restore汇编函数
    
    算法：
    1. 扫描所有提交位，找到最大已提交的WID (W*)
    2. 根据W*，确定需要恢复的地址集合U(W*)
    3. 对每个地址A ∈ U(W*)，恢复其值
    4. 跳转到NextPC[W*]
    """
    lines = []
    
    lines.append("; ============================================")
    lines.append("; ASAP Runtime Restore Logic")
    lines.append("; Auto-generated by generate_restore_asm.py")
    lines.append("; ============================================")
    lines.append("")
    lines.append("\t.global _asap_restore")
    lines.append("\t.section .text")
    lines.append("")
    lines.append("_asap_restore:")
    lines.append("\t; 保存工作寄存器")
    lines.append("\tPUSH\tR12")
    lines.append("\tPUSH\tR13")
    lines.append("\tPUSH\tR14")
    lines.append("\tPUSH\tR15")
    lines.append("")
    
    # 步骤1: 找到最大已提交的WID (W*)
    lines.append("\t; ===== Step 1: Find W* (max committed WID) =====")
    lines.append("\tMOV.W\t#0, R12\t\t; R12 = W* (初始化为0)")
    lines.append("\tMOV.W\t#1, R13\t\t; R13 = current WID (从1开始)")
    lines.append("")
    
    wid_count = metadata.get('statistics', {}).get('total_wids', 180)
    commit_base = 0x7400  # ASAP_COMMITS起始地址
    
    lines.append("find_wstar_loop:")
    lines.append(f"\tCMP.W\t#{wid_count + 1}, R13\t; 检查是否扫描完所有WID")
    lines.append("\tJGE\tfind_wstar_done\t\t; 如果R13 >= 总WID数，跳出")
    lines.append("")
    lines.append("\t; 计算提交位地址: commit_base + (WID - 1)")
    lines.append("\tMOV.W\tR13, R14")
    lines.append("\tSUB.W\t#1, R14\t\t\t; R14 = WID - 1")
    lines.append(f"\tADD.W\t#0x{commit_base:04X}, R14\t; R14 = &C[WID]")
    lines.append("")
    lines.append("\t; 检查提交位")
    lines.append("\tMOV.B\t@R14, R15\t\t; R15 = C[WID]")
    lines.append("\tCMP.B\t#1, R15")
    lines.append("\tJNE\tfind_wstar_next\t\t; 如果未提交，跳过")
    lines.append("")
    lines.append("\t; 更新W*")
    lines.append("\tMOV.W\tR13, R12\t\t; W* = current WID")
    lines.append("")
    lines.append("find_wstar_next:")
    lines.append("\tADD.W\t#1, R13\t\t\t; current WID++")
    lines.append("\tBR\t#find_wstar_loop")
    lines.append("")
    lines.append("find_wstar_done:")
    lines.append("\t; R12 现在包含 W*")
    lines.append("\tCMP.W\t#0, R12")
    lines.append("\tJEQ\trestore_cold_start\t; 如果W*=0，冷启动，不恢复")
    lines.append("")
    
    # 步骤2: 恢复状态
    lines.append("\t; ===== Step 2: Restore state for W* =====")
    lines.append("\t; 简化实现：恢复所有槽位（完整实现需要U(W*)计算）")
    lines.append("\tMOV.W\t#0, R13\t\t; R13 = address index")
    lines.append("")
    
    # 获取地址列表
    writewids = metadata.get('writewids', {})
    addresses = sorted(writewids.keys())
    
    lines.append("restore_loop:")
    lines.append(f"\tCMP.W\t#{len(addresses)}, R13")
    lines.append("\tJGE\trestore_done")
    lines.append("")
    lines.append("\t; TODO: 根据生命周期判断是否需要恢复该地址")
    lines.append("\t; 当前简化版：恢复所有地址")
    lines.append("")
    
    # 为每个地址生成恢复代码（简化版）
    for i, addr in enumerate(addresses[:10]):  # 限制前10个作为示例
        lines.append(f"\t; 恢复地址 {addr}")
        lines.append(f"\tCMP.W\t#{i}, R13")
        lines.append(f"\tJNE\trestore_addr_{i+1}")
        
        # 简化：直接从S0槽位恢复（完整实现需要slot_of(A,W*)查找）
        clean_addr = addr.replace("0x", "").replace("::", "__").replace("(", "_").replace(")", "").upper()
        slot_symbol = f"__RS_S0_{clean_addr}"
        
        lines.append(f"\tMOV.W\t&{slot_symbol}, R14\t; 读取槽位值")
        # addr 包含"::"或"(r1)"，需要转换为汇编可识别的格式
        # 例如 "bit_count::2(r1)" -> 2(r1) (栈相对寻址)
        # 例如 "22(r1)" -> 22(r1) (不需要&)
        if "::" in addr:
            # 提取 "::" 后的部分作为实际地址
            addr_part = addr.split("::")[-1]
            lines.append(f"\tMOV.W\tR14, {addr_part}\t\t; 恢复到目标地址")
        elif "(" in addr:
            # 地址包含括号，说明是寄存器相对寻址（如"22(r1)"），不需要&
            lines.append(f"\tMOV.W\tR14, {addr}\t\t; 恢复到目标地址")
        else:
            # 绝对地址，需要&（如"0x23cc"）
            lines.append(f"\tMOV.W\tR14, &{addr}\t\t; 恢复到目标地址")
        lines.append(f"\tBR\t#restore_next")
        lines.append(f"restore_addr_{i+1}:")
    
    lines.append("")
    lines.append("restore_next:")
    lines.append("\tADD.W\t#1, R13")
    lines.append("\tBR\t#restore_loop")
    lines.append("")
    lines.append("restore_done:")
    lines.append("\t; 清除所有提交位")
    lines.append("\tMOV.W\t#1, R13")
    lines.append("clear_commits_loop:")
    lines.append(f"\tCMP.W\t#{wid_count + 1}, R13")
    lines.append("\tJGE\tclear_commits_done")
    lines.append("\tMOV.W\tR13, R14")
    lines.append("\tSUB.W\t#1, R14")
    lines.append(f"\tADD.W\t#0x{commit_base:04X}, R14")
    lines.append("\tMOV.B\t#0, @R14\t\t; 清除C[WID]")
    lines.append("\tADD.W\t#1, R13")
    lines.append("\tBR\t#clear_commits_loop")
    lines.append("")
    lines.append("clear_commits_done:")
    lines.append("")
    
    # 步骤3: 跳转到NextPC[W*] (正确修复版本)
    lines.append("\t; ===== Step 3: Jump to NextPC[W*] (FIXED) =====")
    lines.append("\tCMP.W\t#0, R12\t\t\t; 检查W*是否为0")
    lines.append("\tJEQ\trestore_cold_start\t; 如果W*=0，冷启动返回")
    lines.append("")
    lines.append("\t; W* > 0：热恢复，需要跳转到NextPC[W*]")
    lines.append("\t; 计算NextPC[W*]地址并读取")
    lines.append("\tMOV.W\tR12, R14\t\t; R14 = W*")
    lines.append("\tSUB.W\t#1, R14\t\t\t; R14 = W* - 1 (数组索引)")
    lines.append("\tRLA.W\tR14\t\t\t; R14 *= 2 (uint16_t是2字节)")
    lines.append("\tMOV.W\t#ASAP_NextPC, R15\t; R15 = &ASAP_NextPC[0]")
    lines.append("\tADD.W\tR15, R14\t\t; R14 = &ASAP_NextPC[W*-1]")
    lines.append("\tMOV.W\t@R14, R14\t\t; R14 = NextPC[W*]")
    lines.append("")
    lines.append("\t; 把NextPC写到栈上（覆盖保存的R15位置）")
    lines.append("\t; 栈布局：SP→[R15][R14][R13][R12]")
    lines.append("\tMOV.W\tR14, 0(SP)\t\t; 栈顶（R15的位置）= NextPC")
    lines.append("")
    lines.append("\t; 恢复寄存器（顺序：R15,R14,R13,R12）")
    lines.append("\tPOP\tR15\t\t\t; R15 = NextPC!")
    lines.append("\tPOP\tR14")
    lines.append("\tPOP\tR13")
    lines.append("\tPOP\tR12")
    lines.append("")
    lines.append("\t; 跳转到NextPC[W*]")
    lines.append("\tMOV.W\tR15, PC\t\t\t; 跳转！")
    lines.append("")
    
    # 冷启动路径
    lines.append("restore_cold_start:")
    lines.append("\t; 冷启动：没有需要恢复的状态")
    lines.append("\tPOP\tR15")
    lines.append("\tPOP\tR14")
    lines.append("\tPOP\tR13")
    lines.append("\tPOP\tR12")
    lines.append("\tRET\t\t\t\t; 返回到bootloader")
    lines.append("")
    
    return lines

def main():
    parser = argparse.ArgumentParser(description="Generate ASAP restore assembly code")
    parser.add_argument("--metadata", required=True, help="Input metadata JSON file")
    parser.add_argument("--output", required=True, help="Output assembly file")
    args = parser.parse_args()
    
    # 加载元数据
    print(f"[generate_restore_asm] 加载元数据: {args.metadata}")
    with open(args.metadata, 'r') as f:
        metadata = json.load(f)
    
    # 生成恢复逻辑
    restore_asm = generate_restore_function(metadata)
    
    # 写入汇编文件
    with open(args.output, 'w') as f:
        f.write('\n'.join(restore_asm))
    
    print(f"[generate_restore_asm] 生成恢复逻辑: {args.output} ({len(restore_asm)} 行)")
    print(f"[generate_restore_asm] 完成！")

if __name__ == "__main__":
    main()

